create extension if not exists pgcrypto;

create table if not exists public.profiles(
 id uuid primary key references auth.users(id) on delete cascade,
 username text not null unique,
 coins integer not null default 0 check(coins>=0),
 equipped_skin_id text not null default 'base',
 created_at timestamptz not null default now()
);
create table if not exists public.skins(
 id text primary key,
 name text not null,
 emoji text not null default '🐰',
 rarity text not null check(rarity in ('Commun','Légendaire')),
 price integer not null check(price>=0),
 description text not null default '',
 theme text not null default 'base',
 published boolean not null default true,
 created_at timestamptz not null default now()
);
create table if not exists public.user_skins(
 user_id uuid not null references public.profiles(id) on delete cascade,
 skin_id text not null references public.skins(id) on delete cascade,
 acquired_at timestamptz not null default now(),
 primary key(user_id,skin_id)
);
create table if not exists public.events(
 id bigint generated by default as identity primary key,
 title text not null,
 body text not null,
 published boolean not null default true,
 created_at timestamptz not null default now()
);


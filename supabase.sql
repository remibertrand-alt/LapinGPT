create or replace function public.new_lapin_profile()
returns trigger language plpgsql security definer set search_path=public as $$
declare uname text;
begin
 uname:=coalesce(nullif(trim(new.raw_user_meta_data->>'username'),''),'Lapinou');
 uname:=left(uname,24);
 if exists(select 1 from public.profiles where username=uname) then uname:=left(uname,18)||'_'||substr(new.id::text,1,5); end if;
 insert into public.profiles(id,username,equipped_skin_id) values(new.id,uname,'base');
 insert into public.user_skins(user_id,skin_id) values(new.id,'base') on conflict do nothing;
 return new;
end; $$;
drop trigger if exists on_auth_user_created_lapin on auth.users;
create trigger on_auth_user_created_lapin after insert on auth.users for each row execute procedure public.new_lapin_profile();

create or replace function public.award_question_coins(p_user_id uuid,p_amount integer)
returns void language plpgsql security definer set search_path=public as $$
begin
 if p_amount<>5 then raise exception 'Montant de récompense invalide'; end if;
 update public.profiles set coins=coins+p_amount where id=p_user_id;
 if not found then raise exception 'Profil introuvable'; end if;
end; $$;

create or replace function public.purchase_skin(p_user_id uuid,p_skin_id text)
returns void language plpgsql security definer set search_path=public as $$
declare s public.skins%rowtype;
begin
 select * into s from public.skins where id=p_skin_id and published=true;
 if not found then raise exception 'Skin indisponible'; end if;
 if exists(select 1 from public.user_skins where user_id=p_user_id and skin_id=p_skin_id) then raise exception 'Tu possèdes déjà ce skin'; end if;
 update public.profiles set coins=coins-s.price where id=p_user_id and coins>=s.price;
 if not found then raise exception 'Pas assez de pièces'; end if;
 insert into public.user_skins(user_id,skin_id) values(p_user_id,p_skin_id);
end; $$;

create or replace function public.equip_skin(p_user_id uuid,p_skin_id text)
returns void language plpgsql security definer set search_path=public as $$
begin
 if not exists(select 1 from public.user_skins where user_id=p_user_id and skin_id=p_skin_id) then raise exception 'Tu ne possèdes pas ce skin'; end if;
 update public.profiles set equipped_skin_id=p_skin_id where id=p_user_id;
end; $$;

alter table public.profiles enable row level security;
alter table public.skins enable row level security;
alter table public.user_skins enable row level security;
alter table public.events enable row level security;

drop policy if exists "Read published skins" on public.skins;
create policy "Read published skins" on public.skins for select to authenticated using(published=true);
drop policy if exists "Read own profile" on public.profiles;
create policy "Read own profile" on public.profiles for select to authenticated using(auth.uid()=id);
drop policy if exists "Read own collection" on public.user_skins;
create policy "Read own collection" on public.user_skins for select to authenticated using(auth.uid()=user_id);
drop policy if exists "Read published events" on public.events;
create policy "Read published events" on public.events for select to authenticated using(published=true);

revoke all on function public.award_question_coins(uuid,integer) from public,anon,authenticated;
